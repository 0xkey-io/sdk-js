import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const packageRoot = fileURLToPath(new URL("../", import.meta.url));
const packageJson = JSON.parse(
  await readFile(new URL("../package.json", import.meta.url), "utf8"),
);
const constants = await readFile(
  new URL("../src/constants.ts", import.meta.url),
  "utf8",
);

function constant(name) {
  const match = constants.match(
    new RegExp(`export const ${name} = [\"']([^\"']+)[\"']`),
  );
  if (!match) throw new Error(`Missing string constant ${name}`);
  return match[1];
}

const dependencies = ["mppx", "@x402/core", "@x402/evm", "@x402/fetch"];
for (const name of dependencies) {
  const version = packageJson.dependencies?.[name];
  if (!version || /^[~^*]|\s|[<>]/.test(version)) {
    throw new Error(`${name} must use one exact version`);
  }
}

const exports = Object.keys(packageJson.exports)
  .filter((entry) => entry !== ".")
  .map((entry) => entry.replace(/^\.\//, ""))
  .sort();

const rows = [
  [
    "Base mainnet",
    constant("NETWORK_BASE"),
    constant("USDC_BASE"),
    "explicit mainnet channel",
  ],
  [
    "Base Sepolia",
    constant("NETWORK_BASE_SEPOLIA"),
    constant("USDC_BASE_SEPOLIA"),
    "explicit testnet channel",
  ],
];

function markdownTable(headers, body) {
  const allRows = [headers, ...body];
  const widths = headers.map((_, index) =>
    Math.max(3, ...allRows.map((row) => row[index].length)),
  );
  const renderRow = (row) =>
    `| ${row.map((cell, index) => cell.padEnd(widths[index])).join(" | ")} |`;
  return [
    renderRow(headers),
    `| ${widths.map((width) => "-".repeat(width)).join(" | ")} |`,
    ...body.map(renderRow),
  ].join("\n");
}

const supportTable = markdownTable(
  ["Network", "CAIP-2", "Canonical USDC", "Use"],
  rows.map((row) => [row[0], `\`${row[1]}\``, `\`${row[2]}\``, row[3]]),
);

const output = `# Generated Pay support facts

This file is generated by \`scripts/generate-doc-facts.mjs\`. Do not edit it by hand.

- Package: \`${packageJson.name}@${packageJson.version}\`
- Protocols: x402 v2 \`exact\`; Machine Payments Protocol \`evm/charge\`
- Merchant frameworks: Express, Hono, Next.js, Fetch/Request core
- Delivery threshold: Base L2 \`CONFIRMED\`
- Interop matrix: x402 and MPP on Base mainnet and Base Sepolia

## Exact protocol dependencies

${dependencies.map((name) => `- \`${name}@${packageJson.dependencies[name]}\``).join("\n")}

## Public subpaths

${exports.map((entry) => `- \`${packageJson.name}/${entry}\``).join("\n")}

## Networks and assets

${supportTable}
`;

await writeFile(
  new URL("../docs/generated-support.md", import.meta.url),
  output,
  "utf8",
);

process.stdout.write(`updated ${packageRoot}docs/generated-support.md\n`);
